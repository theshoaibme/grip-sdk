"""High-performance PDF document generator for Grip AI Agent.

Generates clean, well-formatted, multi-page PDF documents from markdown
or plain text with zero external C-dependencies. Also supports reportlab
or fpdf2 if installed.
"""

from __future__ import annotations

import os
import time
from typing import Any


def _wrap_line(text: str, max_len: int = 80) -> list[str]:
    """Wrap a line of text at word boundaries to fit page width."""
    words = text.split(" ")
    lines: list[str] = []
    cur: list[str] = []
    cur_len = 0
    for w in words:
        if not w:
            continue
        extra = 1 if cur else 0
        if cur_len + len(w) + extra > max_len:
            lines.append(" ".join(cur))
            cur = [w]
            cur_len = len(w)
        else:
            cur.append(w)
            cur_len += len(w) + extra
    if cur:
        lines.append(" ".join(cur))
    return lines or [""]


def generate_pdf(
    output_path: str,
    title: str,
    content: str,
    author: str = "Grip AI Agent",
    page_size: str = "A4",
) -> dict[str, Any]:
    """Generate a valid, multi-page PDF document and save to disk.

    Args:
        output_path: Destination file path (e.g. 'output/report.pdf').
        title: Document title.
        content: Text or markdown content to format into the PDF.
        author: Document author metadata string.
        page_size: 'A4' (default) or 'LETTER'.

    Returns:
        Dictionary with file path, page count, and byte size.
    """
    # 1. Try reportlab if installed for rich typesetting
    try:
        from reportlab.lib.pagesizes import letter, A4
        from reportlab.pdfgen import canvas

        psize = letter if page_size.upper() == "LETTER" else A4
        c = canvas.Canvas(output_path, pagesize=psize)
        c.setTitle(title)
        c.setAuthor(author)

        width, height = psize
        margin_x = 54
        y = height - 54

        # Title
        c.setFont("Helvetica-Bold", 18)
        c.drawString(margin_x, y, title[:80])
        y -= 22

        # Subtitle
        c.setFont("Helvetica-Oblique", 9)
        c.drawString(margin_x, y, f"Author: {author}  |  Generated by Grip AI SDK  |  {time.strftime('%Y-%m-%d %H:%M')}")
        y -= 24

        c.setStrokeColorRGB(0.8, 0.8, 0.8)
        c.setLineWidth(0.5)
        c.line(margin_x, y, width - margin_x, y)
        y -= 20

        paragraphs = content.split("\n")
        for p in paragraphs:
            p_clean = p.strip()
            if not p_clean:
                y -= 10
                continue
            if y < 54:
                c.showPage()
                y = height - 54

            if p_clean.startswith("# "):
                c.setFont("Helvetica-Bold", 14)
                c.drawString(margin_x, y, p_clean[2:][:80])
                y -= 20
            elif p_clean.startswith("## "):
                c.setFont("Helvetica-Bold", 12)
                c.drawString(margin_x, y, p_clean[3:][:85])
                y -= 16
            elif p_clean.startswith("### "):
                c.setFont("Helvetica-Bold", 10.5)
                c.drawString(margin_x, y, p_clean[4:][:90])
                y -= 15
            elif p_clean.startswith(("- ", "* ", "• ")):
                c.setFont("Helvetica", 10)
                bullet_lines = _wrap_line(p_clean[2:], max_len=75)
                for idx, bl in enumerate(bullet_lines):
                    if y < 54:
                        c.showPage()
                        y = height - 54
                    prefix = "• " if idx == 0 else "   "
                    c.drawString(margin_x + 10, y, prefix + bl)
                    y -= 14
            else:
                c.setFont("Helvetica", 10)
                body_lines = _wrap_line(p_clean, max_len=82)
                for bl in body_lines:
                    if y < 54:
                        c.showPage()
                        y = height - 54
                    c.drawString(margin_x, y, bl)
                    y -= 14

        c.save()
        file_size = os.path.getsize(output_path)
        return {
            "success": True,
            "path": os.path.abspath(output_path),
            "size_bytes": file_size,
            "engine": "reportlab",
            "title": title,
        }
    except ImportError:
        pass

    # 2. Built-in zero-dependency Pure Python PDF 1.4 Generator
    out_dir = os.path.dirname(os.path.abspath(output_path))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    formatted_items: list[tuple[str, str]] = []
    formatted_items.append(("title", title))
    formatted_items.append(("meta", f"Author: {author}  |  Generated by Grip AI SDK  |  {time.strftime('%Y-%m-%d %H:%M')}"))
    formatted_items.append(("spacer", ""))

    raw_paragraphs = content.split("\n")
    for p in raw_paragraphs:
        p_str = p.strip()
        if not p_str:
            formatted_items.append(("spacer", ""))
        elif p_str.startswith("# "):
            formatted_items.append(("heading1", p_str[2:].strip()))
        elif p_str.startswith("## "):
            formatted_items.append(("heading2", p_str[3:].strip()))
        elif p_str.startswith("### "):
            formatted_items.append(("heading3", p_str[4:].strip()))
        elif p_str.startswith(("- ", "* ", "• ")):
            for idx, wl in enumerate(_wrap_line(p_str[2:].strip(), max_len=75)):
                prefix = "* " if idx == 0 else "  "
                formatted_items.append(("bullet", prefix + wl))
        else:
            for wl in _wrap_line(p_str, max_len=80):
                formatted_items.append(("body", wl))

    pages_streams: list[bytes] = []
    y = 780
    top_y = 780
    bottom_y = 60

    def start_page() -> list[str]:
        return ["BT", "50 780 Td"]

    cur_page_ops = start_page()

    for itype, itext in formatted_items:
        req_height = 24 if itype in ("title", "heading1") else (18 if itype == "heading2" else 14)
        if y - req_height < bottom_y:
            cur_page_ops.append("ET")
            pages_streams.append("\n".join(cur_page_ops).encode("latin-1", "replace"))
            cur_page_ops = start_page()
            y = top_y

        escaped = itext.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        if itype == "title":
            cur_page_ops.append("/F1 18 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -26 Td")
            y -= 26
        elif itype == "meta":
            cur_page_ops.append("/F3 9 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -18 Td")
            y -= 18
        elif itype == "heading1":
            cur_page_ops.append("/F1 14 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -20 Td")
            y -= 20
        elif itype == "heading2":
            cur_page_ops.append("/F1 12 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -16 Td")
            y -= 16
        elif itype == "heading3":
            cur_page_ops.append("/F1 11 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -15 Td")
            y -= 15
        elif itype == "spacer":
            cur_page_ops.append("0 -10 Td")
            y -= 10
        elif itype == "bullet":
            cur_page_ops.append("/F2 10 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -14 Td")
            y -= 14
        else:  # body
            cur_page_ops.append("/F2 10 Tf")
            cur_page_ops.append(f"({escaped}) Tj")
            cur_page_ops.append("0 -14 Td")
            y -= 14

    cur_page_ops.append("ET")
    pages_streams.append("\n".join(cur_page_ops).encode("latin-1", "replace"))

    num_pages = len(pages_streams)
    page_obj_ids = [3 + i for i in range(num_pages)]
    stream_obj_ids = [3 + num_pages + i for i in range(num_pages)]
    f1_id = 3 + 2 * num_pages
    f2_id = f1_id + 1
    f3_id = f2_id + 1

    objects: dict[int, bytes] = {}
    objects[1] = b"<< /Type /Catalog /Pages 2 0 R >>"
    kids_str = " ".join(f"{pid} 0 R" for pid in page_obj_ids)
    objects[2] = f"<< /Type /Pages /Kids [{kids_str}] /Count {num_pages} >>".encode("ascii")

    for i in range(num_pages):
        pid = page_obj_ids[i]
        sid = stream_obj_ids[i]
        page_dict = f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents {sid} 0 R /Resources << /Font << /F1 {f1_id} 0 R /F2 {f2_id} 0 R /F3 {f3_id} 0 R >> >> >>".encode("ascii")
        objects[pid] = page_dict

        s_bytes = pages_streams[i]
        stream_dict = f"<< /Length {len(s_bytes)} >>\nstream\n".encode("ascii") + s_bytes + b"\nendstream"
        objects[sid] = stream_dict

    objects[f1_id] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"
    objects[f2_id] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
    objects[f3_id] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"

    total_objs = max(objects.keys())
    out: list[bytes] = [b"%PDF-1.4\n"]
    offsets: dict[int, int] = {}
    for oid in sorted(objects.keys()):
        offsets[oid] = sum(len(x) for x in out)
        out.append(f"{oid} 0 obj\n".encode("ascii") + objects[oid] + b"\nendobj\n")

    xref_offset = sum(len(x) for x in out)
    out.append(f"xref\n0 {total_objs + 1}\n0000000000 65535 f \n".encode("ascii"))
    for oid in range(1, total_objs + 1):
        off = offsets.get(oid, 0)
        out.append(f"{off:010d} 00000 n \n".encode("ascii"))
    out.append(f"trailer\n<< /Size {total_objs + 1} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n".encode("ascii"))

    pdf_bytes = b"".join(out)
    with open(output_path, "wb") as f:
        f.write(pdf_bytes)

    return {
        "success": True,
        "path": os.path.abspath(output_path),
        "size_bytes": len(pdf_bytes),
        "pages": num_pages,
        "engine": "native_pure_python",
        "title": title,
    }
